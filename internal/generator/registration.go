package generator

import (
	"fmt"
	"go/format"
	"slices"
	"strings"
)

func Registration(kinds []Kind, header []byte) ([]byte, error) {
	groups := make([]string, 0, len(kinds))
	for _, k := range kinds {
		groups = append(groups, k.Group)
	}
	slices.Sort(groups)
	var imports, funcs strings.Builder
	for _, group := range slices.Compact(groups) {
		fmt.Fprintf(&imports, "%s%s %q\n", group, version, apisModule+"/"+group+"/"+version)
		fmt.Fprintf(&funcs, "%s%s.SchemeBuilder.AddToScheme,\n", group, version)
	}
	return format.Source(fmt.Appendf(nil, `%s
// Code generated by cmd/generator. DO NOT EDIT.

package apis

import (
	"k8s.io/apimachinery/pkg/runtime"

	%s)

func generatedGroups() []func(*runtime.Scheme) error {
	return []func(*runtime.Scheme) error{
		%s}
}
`, header, imports.String(), funcs.String()))
}
