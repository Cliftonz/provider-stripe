const kitPackage = "github.com/Cliftonz/provider-stripe/internal/controller/kit"

var pathParam = regexp.MustCompile(`\{[^}/]+\}`)

func Wiring(spec []byte, kinds []Kind, header []byte) (map[string][]byte, []byte, error) {
	var doc typesDoc
	if err := json.Unmarshal(spec, &doc); err != nil {
		return nil, nil, err
	}
	methods := map[string]*strings.Builder{}
	var setup, gated, descriptors strings.Builder
	for _, k := range kinds {
		object, err := responseObject(doc, k.ItemPath)
		if err != nil {
			return nil, nil, err
		}
		lateInit, err := lateInitFields(doc, k, object)
		if err != nil {
			return nil, nil, err
		}
		if methods[k.Group] == nil {
			methods[k.Group] = &strings.Builder{}
		}
		secrets := secretFields(k.Path, object)
		writeMethods(methods[k.Group], k.Name, object, secrets)
		pkg := k.Group + version
		args := fmt.Sprintf("mgr, o, %[1]s.SchemeGroupVersion.WithKind(%[2]q), &%[1]s.%[2]s{}, &%[1]s.%[2]sList{}, %[3]s%[2]s) },\n", pkg, k.Name, k.Group)
		setup.WriteString("func() error { return kit.Setup(" + args)
		gated.WriteString("func() error { return kit.SetupGated(" + args)
		writeDescriptor(&descriptors, k, lateInit, secrets)
	}
	files := map[string][]byte{}
	for group, b := range methods {
		src, err := format.Source([]byte(fmt.Sprintf("%s\n// Code generated by cmd/generator. DO NOT EDIT.\n\npackage %s\n\nimport %q\n%s", header, version, kitPackage, b)))
		if err != nil {
			return nil, nil, err
		}
		files[group+"/"+version+"/kit.go"] = src
	}
	var imports strings.Builder
	for _, group := range slices.Sorted(maps.Keys(methods)) {
		fmt.Fprintf(&imports, "%s%s %q\n", group, version, apisModule+"/"+group+"/"+version)
	}
	src, err := format.Source(fmt.Appendf(nil, `%s
// Code generated by cmd/generator. DO NOT EDIT.

package controller

import (
	"github.com/crossplane/crossplane-runtime/v2/pkg/controller"
	ctrl "sigs.k8s.io/controller-runtime"

	%s"github.com/Cliftonz/provider-stripe/internal/controller/kit"
)

func Setup(mgr ctrl.Manager, o controller.Options) error {
	return run(
		%s)
}

func SetupGated(mgr ctrl.Manager, o controller.Options) error {
	return run(
		%s)
}

func run(setups ...func() error) error {
	for _, setup := range setups {
		if err := setup(); err != nil {
			return err
		}
	}
	return nil
}

var (%s)
`, header, imports.String(), setup.String(), gated.String(), descriptors.String()))
	return files, src, err
}

func lateInitFields(doc typesDoc, k Kind, object *schema) ([]string, error) {
	create := doc.Paths[k.Path].Post.RequestBody.Content[formContentType].Schema
	var fields []string
	for _, name := range slices.Sorted(slices.Values(append(slices.Clone(k.CreateFields), k.UpdateOnlyFields...))) {
		observed := object.Properties[name]
		if slices.Contains(create.Required, name) || observed == nil || observed.Nullable {
			continue
		}
		s, path := paramSchema(doc, k, name)
		f, err := (&kindGen{path: path}).param(s, "", name, name, false)
		if err != nil {
			return nil, err
		}
		if f.Type == "*"+scalarTypes[observed.Type] && withinEnum(observed.Enum, requestEnum(s)) {
			fields = append(fields, name)
		}
	}
	return fields, nil
}

func requestEnum(s *schema) []any {
	for _, branch := range s.AnyOf {
		if !isEmptyString(branch) {
			return branch.Enum
		}
	}
	return s.Enum
}

func withinEnum(values, allowed []any) bool {
	if len(allowed) == 0 {
		return true
	}
	if len(values) == 0 {
		return false
	}
	for _, v := range values {
		if !slices.Contains(allowed, v) {
			return false
		}
	}
	return true
}

func writeMethods(b *strings.Builder, name string, object *schema, secrets []string) {
	fmt.Fprintf(b, `
func (mg *%[1]s) GetParameters() any {
	return &mg.Spec.ForProvider
}

func (mg *%[1]s) SetObservation(o map[string]any) {
	kit.Observe(o, &mg.Status.AtProvider, map[string]string{
`, name)
	for _, key := range slices.Sorted(maps.Keys(object.Properties)) {
		if !slices.Contains(secrets, key) {
			_, jsonName, _ := names(key)
			fmt.Fprintf(b, "%q: %q,\n", key, jsonName)
		}
	}
	b.WriteString("})\n}\n")
}

func writeDescriptor(b *strings.Builder, k Kind, lateInit, secrets []string) {
	fmt.Fprintf(b, "\n%s%s = kit.Descriptor{\nCollectionPath: %q,\nItemPath: %q,\n", k.Group, k.Name, k.Path, pathParam.ReplaceAllString(k.ItemPath, "%s"))
	for _, f := range []struct {
		name   string
		values []string
	}{{"UpdatableFields", k.UpdatableFields}, {"LateInitFields", lateInit}, {"UpdateOnlyFields", k.UpdateOnlyFields}, {"SecretFields", secrets}} {
		if len(f.values) > 0 {
			fmt.Fprintf(b, "%s: %#v,\n", f.name, f.values)
		}
	}
	d := k.Deletion
	b.WriteString("Deletion: kit.Deletion{Mode: kit." + string(d.Mode))
	for _, f := range [][2]string{{"Action", d.Action}, {"Field", d.Field}, {"Value", d.Value}} {
		if f[1] != "" {
			fmt.Fprintf(b, ", %s: %q", f[0], f[1])
		}
	}
	if len(d.EndStatuses) > 0 {
		fmt.Fprintf(b, ", EndStatuses: %#v", d.EndStatuses)
	}
	if len(d.EndTimestamps) > 0 {
		fmt.Fprintf(b, ", EndTimestamps: %#v", d.EndTimestamps)
	}
	b.WriteString("},\n")
	if slices.Contains(moneyMovers, k.Path) {
		b.WriteString("MovesMoney: true,\n")
	}
	b.WriteString("}\n")
}
